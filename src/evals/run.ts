/**
 * Eval + cost/latency benchmark across providers.
 *
 *   npx tsx src/evals/run.ts                 # every configured provider
 *   npx tsx src/evals/run.ts anthropic       # one vendor
 *   npx tsx src/evals/run.ts google
 *
 * Grades behaviour (tool routing, disambiguation, no-hallucination) and measures the real
 * cost + latency of each answer. Writes a markdown summary to BENCHMARK.md.
 */
import { writeFileSync } from "node:fs";
import dotenv from "dotenv";
import { runAgent } from "@/lib/agent/run";
import { computeCost } from "@/lib/cost";
import { warmCatalog } from "@/lib/ffbb";
import { getProvider, providerAvailable, type Vendor } from "@/lib/llm";
import { addUsage, zeroUsage } from "@/lib/llm/types";
import { CASES } from "./cases";

dotenv.config({ path: ".env.local" });
dotenv.config(); // fall back to .env

interface Row {
  vendor: Vendor;
  model: string;
  passed: number;
  total: number;
  avgMs: number;
  avgUsd: number;
  avgTokens: number;
}

async function benchVendor(vendor: Vendor): Promise<Row> {
  const provider = getProvider(vendor);
  const catalog = await warmCatalog();
  console.log(`\n=== ${provider.label} ===`);

  let passed = 0;
  let totalMs = 0;
  let totalUsd = 0;
  let usage = zeroUsage();

  for (const c of CASES) {
    const t0 = Date.now();
    let ok = false;
    let note = "";
    try {
      const result = await runAgent(provider, [], c.question, catalog);
      const graded = c.check(result);
      ok = graded.pass;
      note = graded.reason;
      totalUsd += computeCost(provider.model, result.usage).usd;
      usage = addUsage(usage, result.usage);
    } catch (e) {
      note = `ERROR ${(e as Error).message}`;
    }
    const ms = Date.now() - t0;
    totalMs += ms;
    if (ok) passed++;
    console.log(`  ${ok ? "✓" : "✗"} ${c.id.padEnd(20)} ${String(ms).padStart(5)}ms  ${note}`);
  }

  const n = CASES.length;
  return {
    vendor,
    model: provider.model,
    passed,
    total: n,
    avgMs: Math.round(totalMs / n),
    avgUsd: totalUsd / n,
    avgTokens: Math.round((usage.inputTokens + usage.cacheReadTokens + usage.cacheWriteTokens + usage.outputTokens) / n),
  };
}

function markdownTable(rows: Row[]): string {
  const head =
    "| Provider | Model | Pass | Avg latency | Avg cost/answer | Avg tokens | Cost / 1k answers |\n" +
    "|---|---|---|---|---|---|---|";
  const body = rows
    .map(
      (r) =>
        `| ${r.vendor} | \`${r.model}\` | ${r.passed}/${r.total} | ${r.avgMs} ms | $${r.avgUsd.toFixed(5)} | ${r.avgTokens} | $${(r.avgUsd * 1000).toFixed(2)} |`,
    )
    .join("\n");
  return `${head}\n${body}`;
}

async function main() {
  const requested = process.argv.slice(2).filter((a): a is Vendor => a === "anthropic" || a === "google");
  const vendors: Vendor[] = (requested.length ? requested : (["anthropic", "google"] as Vendor[])).filter((v) => {
    if (!providerAvailable(v)) {
      console.log(`(skipping ${v} — no API key configured)`);
      return false;
    }
    return true;
  });

  if (vendors.length === 0) {
    console.error("No provider configured. Set ANTHROPIC_API_KEY and/or GEMINI_API_KEY in .env.local.");
    process.exit(1);
  }

  const rows: Row[] = [];
  for (const v of vendors) rows.push(await benchVendor(v));

  const table = markdownTable(rows);
  console.log(`\n${table}\n`);

  const md = `# Benchmark\n\n${CASES.length} behavioural cases over live FFBB data, graded on tool routing and no-hallucination.\n\n${table}\n\n_Generated by \`npm run eval\`. Costs use the rates in \`src/lib/cost.ts\`._\n`;
  writeFileSync("BENCHMARK.md", md);
  console.log("Wrote BENCHMARK.md");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
